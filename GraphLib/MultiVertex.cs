using System.Collections.Generic;

namespace GraphLib
{
    //--------------------------------------------------------------------------------------
    // class MultiVertex
    //--------------------------------------------------------------------------------------
    public class MultiVertex
    {
        public int Ind { get; set; }
        public List<MultiEdge> Edges { get; private set; }
        //-------------------------------------------------------------------------------------------------------
        public string Name
        {
            get
            {
                return Ind.ToString();
            }
        }
        //-------------------------------------------------------------------------------------------------------
        public int Weight
        {
            get
            {
                return Edges.Count;
            }
        }
        //--------------------------------------------------------------------------------------
        public MultiVertex()
        {
        }
        //--------------------------------------------------------------------------------------
        public MultiVertex( int ind)
        {
            Ind = ind;
            Edges = new List<MultiEdge>();
        }
        //--------------------------------------------------------------------------------------

    }
    //--------------------------------------------------------------------------------------
}
